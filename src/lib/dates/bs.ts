const ISO_DATE = /^(\d{4})-(\d{2})-(\d{2})$/;

/** A BS date: month 1 is Baisakh. */
export type BsDate = { year: number; month: number; day: number };

/** The AD date ("YYYY-MM-DD") in BS, or null when it isn't a real date or is outside the table. */
export function adToBs(iso: string): BsDate | null {
  const days = daysSinceTableStart(iso);
  if (days === null || days < 0) return null;
  let left = days;
  for (const [yearIndex, months] of MONTH_DAYS.entries()) {
    const inYear = sum(months);
    if (left < inYear) return { year: FIRST_BS_YEAR + yearIndex, ...monthAndDay(months, left) };
    left -= inYear;
  }
  return null;
}

/** The month (1 is Baisakh) and day of the year's `dayOfYear`th day, counting from 0. */
function monthAndDay(months: readonly number[], dayOfYear: number): Omit<BsDate, "year"> {
  let left = dayOfYear;
  let month = 0;
  while (left >= (months[month] ?? Infinity)) {
    left -= months[month] ?? 0;
    month += 1;
  }
  return { month: month + 1, day: left + 1 };
}

function sum(values: readonly number[]): number {
  return values.reduce((total, value) => total + value, 0);
}

/** The AD date written in BS, e.g. "2026-11-02" -> "16 Kartik 2083"; "—" when there is none. */
export function formatBsDate(iso: string): string {
  const bs = adToBs(iso);
  if (bs === null) return "—";
  return `${String(bs.day)} ${BS_MONTHS[bs.month - 1] ?? ""} ${String(bs.year)}`;
}

function daysSinceTableStart(iso: string): number | null {
  const match = ISO_DATE.exec(iso);
  if (match === null) return null;
  const [year, month, day] = [Number(match[1]), Number(match[2]), Number(match[3])];
  const moment = new Date(Date.UTC(year, month - 1, day));
  const isRealDate = moment.getUTCMonth() === month - 1 && moment.getUTCDate() === day;
  return isRealDate ? moment.getTime() / MS_PER_DAY - FIRST_DAY : null;
}

/** How many days the BS month has (month 1 is Baisakh), or null outside the table. */
export function bsMonthDays(year: number, month: number): number | null {
  return MONTH_DAYS[year - FIRST_BS_YEAR]?.[month - 1] ?? null;
}

/** The BS date as an AD date ("YYYY-MM-DD"), or null when it isn't a real BS date in the table. */
export function bsToAd(bs: BsDate): string | null {
  if (!isBsDate(bs)) return null;
  const yearIndex = bs.year - FIRST_BS_YEAR;
  const daysInYearsBefore = sum(MONTH_DAYS.slice(0, yearIndex).map(sum));
  const daysInMonthsBefore = sum((MONTH_DAYS[yearIndex] ?? []).slice(0, bs.month - 1));
  const days = daysInYearsBefore + daysInMonthsBefore + bs.day - 1;
  return new Date((FIRST_DAY + days) * MS_PER_DAY).toISOString().slice(0, "YYYY-MM-DD".length);
}

/** Whether the BS date is a real day the table covers. */
function isBsDate({ year, month, day }: BsDate): boolean {
  const length = bsMonthDays(year, month);
  const isWhole = [year, month, day].every(Number.isInteger);
  return isWhole && length !== null && day >= 1 && day <= length;
}
